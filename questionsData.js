/**
 * Detects if a question prompt asks the learner for their personal identity,
 * registration details, email, full name, class/stream, or student ID.
 * Since learners are already authenticated and registered, these questions
 * are strictly prohibited from test papers.
 */
export function isIdentityOrRegistrationQuestion(prompt) {
  if (!prompt || typeof prompt !== "string") return false;
  const p = prompt.trim().toLowerCase();

  // Exact or short demographic field names
  if (/^(email|e-mail|email address|student email|full name|name of student|student name|learner name|name|class|class\/stream|class level|student id|index number)[:\s?.]*$/i.test(p)) {
    return true;
  }

  // Asking for student's email
  if (
    /(enter|type|provide|input|write|what is|state|fill in)\s+(your\s+)?(email|e-mail|gmail|email address)/i.test(p) ||
    /(your|student|candidate|learner)\s+(email|email address)/i.test(p) ||
    /^(email address|student email)\s*[:?]/i.test(p)
  ) {
    return true;
  }

  // Asking for student's full name
  if (
    /(enter|type|provide|input|write|what is|state|fill in)\s+(your\s+)?(full\s+name|surname|first\s+name|student\s+name|learner\s+name|name)/i.test(p) ||
    /(your|student|candidate|learner)\s+(full\s+name|name)/i.test(p) ||
    /^(full name|name of student|candidate name|student's name)\s*[:?]/i.test(p)
  ) {
    return true;
  }

  // Asking for student's class / stream
  if (
    /(enter|select|choose|indicate|state|what is|which)\s+(your\s+)?(class|stream|class\s+level|class\s+track|grade)/i.test(p) ||
    /(which|what)\s+class\s+(do you belong|are you in)/i.test(p) ||
    /^(class|class\s*\/stream|select class)\s*[:?]/i.test(p) ||
    /\b(select\s+class\s+\(basic\s+9a\s+or\s+9b\))\b/i.test(p)
  ) {
    return true;
  }

  // Asking for student ID or Index number
  if (
    /(enter|type|provide|input|write|what is|state|fill in)\s+(your\s+)?(student\s+id|index\s+number|id\s+number|registration\s+number)/i.test(p) ||
    /^(student id|index number|candidate id)\s*[:?]/i.test(p)
  ) {
    return true;
  }

  return false;
}

/**
 * Filters an array of questions, automatically stripping out any personal
 * registration or identity questions (Email, Full Name, Class, etc.)
 */
export function filterValidCurriculumQuestions(questions) {
  if (!Array.isArray(questions)) return [];
  return questions.filter(q => q && !isIdentityOrRegistrationQuestion(q.prompt));
}

/**
 * Returns all configured question packs from localStorage or defaults,
 * strictly sanitized to ensure no personal registration questions exist.
 */
export function getAllConfiguredQuestionPacks() {
  const local = localStorage.getItem("jhs_configured_questions");
  if (local) {
    try {
      const parsed = JSON.parse(local);
      const cleaned = {};
      for (const key of Object.keys(parsed)) {
        cleaned[key] = {
          ...parsed[key],
          questions: filterValidCurriculumQuestions(parsed[key]?.questions || [])
        };
      }
      return { ...ALL_OFFICIAL_QUESTION_PACKS, ...cleaned };
    } catch (e) {
      console.warn("Error parsing jhs_configured_questions:", e);
    }
  }
  return { ...ALL_OFFICIAL_QUESTION_PACKS };
}

/**
 * Persists an edited or newly added question in an assessment pack
 */
export function saveConfiguredQuestion(asmtId, questionData, isNew = false) {
  // Guard against personal registration questions
  if (isIdentityOrRegistrationQuestion(questionData?.prompt)) {
    throw new Error("Invalid Question: Learners must not be asked for their email, full name, class, or student ID. These details are already captured and authenticated by the system.");
  }

  const allPacks = getAllConfiguredQuestionPacks();
  const pack = allPacks[asmtId] || {
    id: asmtId,
    title: "Computing Assessment Sitting",
    subject: "Computing",
    class_level: "Basic 9",
    total_points: 20,
    time_limit_minutes: 15,
    questions: []
  };

  const questions = filterValidCurriculumQuestions(pack.questions || []);
  if (isNew) {
    const newId = `Q-${Date.now()}`;
    questions.push({ ...questionData, id: newId });
  } else {
    const idx = questions.findIndex(q => q.id === questionData.id);
    if (idx >= 0) {
      questions[idx] = { ...questions[idx], ...questionData };
    } else {
      questions.push(questionData);
    }
  }

  const updatedPack = { ...pack, questions };
  allPacks[asmtId] = updatedPack;

  try {
    localStorage.setItem("jhs_configured_questions", JSON.stringify(allPacks));
  } catch (e) {
    console.error("Failed to save configured questions:", e);
  }

  return updatedPack;
}

/**
 * Deletes a question from an assessment pack
 */
export function deleteConfiguredQuestion(asmtId, questionId) {
  const allPacks = getAllConfiguredQuestionPacks();
  if (!allPacks[asmtId]) return null;

  const pack = allPacks[asmtId];
  const questions = (pack.questions || []).filter(q => q.id !== questionId);
  const updatedPack = { ...pack, questions };
  allPacks[asmtId] = updatedPack;

  try {
    localStorage.setItem("jhs_configured_questions", JSON.stringify(allPacks));
  } catch (e) {
    console.error("Failed to persist question deletion:", e);
  }

  return updatedPack;
}

