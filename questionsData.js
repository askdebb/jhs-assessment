/**
 * Returns assessment question pack mapped by assessment ID, learner class level, and optional title.
 * STRICT ENFORCEMENT: Basic 9A learners get 9A questions. Basic 9B learners get 9B questions.
 * All personal registration questions are sanitized out.
 */
export function getAssessmentQuestionPack(asmtId, classLevel = "Basic 9A", asmtTitle = "") {
  const isClass9B = classLevel && (classLevel.includes("9B") || classLevel.includes("3B") || classLevel === "9B");
  const cleanTitle = (asmtTitle || "").toLowerCase();

  let resolvedPack = null;

  // 1. Check if admin configured custom questions in localStorage
  const allPacks = getAllConfiguredQuestionPacks();
  if (allPacks[asmtId] && allPacks[asmtId].questions && allPacks[asmtId].questions.length > 0) {
    resolvedPack = allPacks[asmtId];
  } else if (isClass9B && allPacks[`${asmtId}-9B`] && allPacks[`${asmtId}-9B`].questions?.length > 0) {
    // Check parallel 9B track custom pack
    resolvedPack = allPacks[`${asmtId}-9B`];
  } else if (asmtId === "asmt-002") {
    // 2. Direct Assessment ID resolution
    resolvedPack = COMPUTING_CAT1_9B;
  } else if (asmtId === "asmt-001") {
    resolvedPack = isClass9B ? COMPUTING_CAT1_9B : COMPUTING_CAT1_9A;
  } else if (asmtId === "asmt-006" || asmtId === "asmt-005-9B") {
    resolvedPack = COMPUTING_CAT2_9B;
  } else if (asmtId === "asmt-005") {
    resolvedPack = isClass9B ? COMPUTING_CAT2_9B : COMPUTING_CAT2_9A;
  } else if (cleanTitle.includes("cat 2") || cleanTitle.includes("cat2") || cleanTitle.includes("cat 3")) {
    // 3. Title & Subject based resolution
    resolvedPack = isClass9B ? COMPUTING_CAT2_9B : COMPUTING_CAT2_9A;
  } else if (cleanTitle.includes("cat 1") || cleanTitle.includes("cat1")) {
    resolvedPack = isClass9B ? COMPUTING_CAT1_9B : COMPUTING_CAT1_9A;
  } else {
    // Fallback to respective track CAT 1
    resolvedPack = isClass9B ? COMPUTING_CAT1_9B : COMPUTING_CAT1_9A;
  }

  if (!resolvedPack) return null;

  const customConfig = allPacks[asmtId] || {};
  return {
    ...resolvedPack,
    time_limit_minutes: customConfig.time_limit_minutes || resolvedPack.time_limit_minutes || 15,
    questions: filterValidCurriculumQuestions(resolvedPack.questions || [])
  };
}

/**
 * Fisher-Yates array shuffle for strict cryptographic/algorithmic non-bias
 */
export function shuffleArray(array) {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Anti-Cheating Randomization Engine:
 * Generates an individualized question paper for a specific student.
 * 1. Strictly filters out any personal registration or identity queries (email, name, class).
 * 2. Shuffles the question order so Question 1 for Student A != Question 1 for Student B
 * 3. Shuffles the options inside each question (if MCQ)
 * 4. Preserves correct answer and accepted answer metadata secretly for grading
 */
export function generateStudentPaper(questionPack) {
  if (!questionPack || !questionPack.questions) return [];
  
  // Learners are already authenticated with verified Email, Name, and Class.
  // Never present personal identity or demographic questions.
  const pureQuestions = filterValidCurriculumQuestions(questionPack.questions);

  // 1. Shuffle question order (Student A != Student B)
  const shuffledQuestions = shuffleArray(pureQuestions);

  // 2. Shuffle choices within each question if options exist
  return shuffledQuestions.map((q, index) => {
    const isMcq = Array.isArray(q.options) && q.options.length > 0;
    const shuffledOptions = isMcq ? shuffleArray(q.options) : [];
    return {
      id: q.id,
      originalIndex: index + 1,
      prompt: q.prompt,
      points: q.points || 2,
      type: q.type || (isMcq ? "mcq" : "fill_blank"),
      options: shuffledOptions,
      correctAnswer: q.correctAnswer,
      acceptedAnswers: q.acceptedAnswers || (q.correctAnswer ? [q.correctAnswer] : []),
      explanation: q.explanation || ""
    };
  });
}

