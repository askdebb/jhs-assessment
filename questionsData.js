/**
 * Returns assessment question pack mapped by assessment ID, learner class level, and optional title.
 * STRICT ENFORCEMENT: Basic 9A learners get 9A questions. Basic 9B learners get 9B questions.
 * They are NEVER mixed!
 */
export function getAssessmentQuestionPack(asmtId, classLevel = "Basic 9A", asmtTitle = "") {
  const isClass9B = classLevel && (classLevel.includes("9B") || classLevel.includes("3B") || classLevel === "9B");
  const cleanTitle = (asmtTitle || "").toLowerCase();

  // 1. Direct Assessment ID resolution
  if (asmtId === "asmt-002") {
    return COMPUTING_CAT1_9B;
  }
  if (asmtId === "asmt-001") {
    return isClass9B ? COMPUTING_CAT1_9B : COMPUTING_CAT1_9A;
  }
  if (asmtId === "asmt-005") {
    return isClass9B ? COMPUTING_CAT2_9B : COMPUTING_CAT2_9A;
  }
  if (asmtId === "asmt-003") {
    return isClass9B ? MATH_CAT1_9B : MATH_CAT1_9A;
  }
  if (asmtId === "asmt-004" || asmtId === "asmt-006") {
    return isClass9B ? CREATIVE_ARTS_CAT1_9B : CREATIVE_ARTS_CAT1_9A;
  }

  // 2. Title & Subject based resolution
  if (cleanTitle.includes("math")) {
    return isClass9B ? MATH_CAT1_9B : MATH_CAT1_9A;
  }
  if (cleanTitle.includes("creative") || cleanTitle.includes("art")) {
    return isClass9B ? CREATIVE_ARTS_CAT1_9B : CREATIVE_ARTS_CAT1_9A;
  }
  if (cleanTitle.includes("cat 2") || cleanTitle.includes("algorithm") || cleanTitle.includes("scratch")) {
    return isClass9B ? COMPUTING_CAT2_9B : COMPUTING_CAT2_9A;
  }

  // 3. Fallback to Computing CAT 1 in respective track
  return isClass9B ? COMPUTING_CAT1_9B : COMPUTING_CAT1_9A;
}

/**
 * Fisher-Yates array shuffle for strict cryptographic/algorithmic non-bias
 */
export function shuffleArray(array) {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Anti-Cheating Randomization Engine:
 * Generates an individualized question paper for a specific student.
 * 1. Clones the question list
 * 2. Shuffles the question order so Question 1 for Student A != Question 1 for Student B
 * 3. Shuffles the options inside each question so Option A != Option A for another student
 * 4. Preserves the correct answer verification metadata secretly
 */
export function generateStudentPaper(questionPack) {
  if (!questionPack || !questionPack.questions) return [];
  
  // 1. Shuffle question order (Student A != Student B)
  const shuffledQuestions = shuffleArray(questionPack.questions);

  // 2. Shuffle choices within each question (Option A for Student A != Option A for Student B)
  return shuffledQuestions.map((q, index) => {
    const shuffledOptions = shuffleArray(q.options || []);
    return {
      id: q.id,
      originalIndex: index + 1,
      prompt: q.prompt,
      points: q.points || 2,
      options: shuffledOptions,
      correctAnswer: q.correctAnswer, // Maintained secretly for grading
      explanation: q.explanation || ""
    };
  });
}

